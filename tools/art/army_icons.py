"""Map army counter (tinted plate) and soldier sprite. Writes assets/src/pixel/icons/*.txt."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from pixlib import blank, paste, layer, outline, write

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "assets", "src", "pixel", "icons")

# army_counter: 24x14 plate, grey ramp only (map_view tints it with the nation colour).
# Left bay (darker) holds the soldier sprite, the regiment count is drawn on the right.
W, H = 24, 14
plate = blank(W, H)
for y in range(1, H - 1):
    for x in range(1, W - 1):
        if (x, y) in ((1, 1), (W - 2, 1), (1, H - 2), (W - 2, H - 2)):
            continue
        c = "w"
        if y == 1 or x == 1:
            c = "w"
        if y >= H - 3 or x >= W - 3:
            c = "g" if (y == H - 2 or x == W - 2) else "a"
        if 2 <= x <= 9 and 2 <= y <= H - 3:
            c = "d" if (x == 9 or y == H - 3) else "g"
        plate[y][x] = c
plate = outline(plate, diagonal=False)

# army_unit: steel pikeman, untinted, 10x12, drawn over the counter's bay
unit = layer([
    "......w.",
    "......a.",
    "..aag.a.",
    ".awaag.a",
    "gggggggd",
    "..QPQ..d",
    ".awaaa.d",
    "awwaaagd",
    "awaaag.d",
    ".aaag..d",
    ".g..g...",
    ".d..d...",
], 1, 1, 10, 14)

# army_moving: small gold arrow badge shown next to marching armies
arrow = layer([
    "....Y..",
    "YYYYGG.",
    "GGGGGGD",
    "DDDDGD.",
    "....D..",
], 1, 1, 9, 7)

if __name__ == "__main__":
    write(os.path.join(OUT, "army_counter.txt"), plate, "army_counter – map army counter plate, 24x14 grid, export x2 = 48x28.\nGrey ramp + ink only: map_view.gd tints it with the nation colour. Generated by tools/art/army_icons.py")
    write(os.path.join(OUT, "army_unit.txt"), unit, "army_unit – steel pikeman drawn in the counter's left bay (untinted), 10x14 grid. Generated by tools/art/army_icons.py")
    write(os.path.join(OUT, "army_moving.txt"), arrow, "army_moving – gold march arrow badge, 8x8 grid. Generated by tools/art/army_icons.py")
    print("army_counter army_unit army_moving")
